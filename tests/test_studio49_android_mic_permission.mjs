import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {describeMicFailure} from '../studio-ui/src/services/audioDiagnostics.ts';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const manifest=read('android/app/src/main/AndroidManifest.xml');
const java=read('android/app/src/main/java/vn/hnl/xaydung/hnlmark/MainActivity.java');
const gradle=read('android/app/build.gradle');
assert.match(manifest,/<uses-permission android:name="android\.permission\.RECORD_AUDIO"\s*\/>/);
assert.match(manifest,/<uses-permission android:name="android\.permission\.MODIFY_AUDIO_SETTINGS"\s*\/>/);
assert.doesNotMatch(manifest,/android:name="android\.permission\.MODIFY_AUDIO_SETTINGS"[^>]*maxSdkVersion/);
assert.match(java,/PermissionRequest\.RESOURCE_AUDIO_CAPTURE/);
assert.match(java,/Manifest\.permission\.RECORD_AUDIO/);
assert.match(gradle,/versionCode 2547/);
assert.match(gradle,/applicationIdSuffix '\.trial2574'/);
assert.match(gradle,/versionName '2\.5\.47'/);
assert.match(gradle,/versionNameSuffix '-studio-test'/);
const issue=describeMicFailure({name:'NotReadableError',message:'Could not start audio source'});
assert.match(issue,/WebView/);
assert.doesNotMatch(issue,/Micro đang bị ứng dụng khác sử dụng/);
assert.match(describeMicFailure({name:'NotAllowedError'}),/Quyền micro/);
console.log('PASS TEST49: WebView mic routing permission, native resource grant, truthful error and parallel APK');
